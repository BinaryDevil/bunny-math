type Key = keyof typeof explanationMessages.en;
type ParametersOf<S extends string> = S extends `${string}{${infer Name}}${infer Rest}` ? Name | ParametersOf<Rest> : never;
type Values<K extends Key> = Record<ParametersOf<(typeof explanationMessages.en)[K]>, string | number>;

export function explanationText<K extends Key>(language: Language, key: K, values: Values<K>): string {
  const messages: Record<Key, string> = explanationMessages[language];
  return messages[key].replace(/\{(\w+)\}/g, (_, name: string) => String((values as Record<string, string | number>)[name]));
}
